# Sinônimos / Aliases para retrocompatibilidade
RPG_ICON_ALIASES: Final[dict[str, str]] = {
    "fire": "flame",
    "flask": "activity",
    "gem": "database",
    "rune": "brain",
}


def get_rpg_icon_svg(icon_name: str | None, class_name: str = "w-8 h-8") -> str:
    """Gera marcação SVG limpa e escalável para o ícone especificado.

    Fallback padrão: 'scroll' se o ícone não for reconhecido.
    """
    key = (icon_name or "").strip().lower()
    key = RPG_ICON_ALIASES.get(key, key)
    path = RPG_ICON_PATHS.get(key)

    if not path:
        path = RPG_ICON_PATHS["scroll"]

    return (
        f'<svg class="{class_name}" viewBox="0 0 512 512" fill="currentColor" '
        f'xmlns="http://www.w3.org/2000/svg" aria-hidden="true">'
        f'<path d="{path}"/>'
        f"</svg>"
    )
